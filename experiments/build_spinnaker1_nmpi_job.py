"""Package a frozen hardware run as one NMPI job, without a public Git clone.

The embedded ZIP carries source, selected model files and the declared input
archive. NMPI receives it through its normal authenticated script submission.
This changes delivery of the job, not its model or hardware execution settings.
"""
from __future__ import annotations

import argparse
import base64
import io
import json
from pathlib import Path
import zipfile


SEEDS = (1701, 2718, 3141, 5772, 8119)
VARIANTS = ("original", "reset_repaired")


def build_job(runtime: Path, bundle: Path, inputs: Path, *, seeds=SEEDS,
              start=0, count=1, time_scale_factor=100,
              run_output="batch_shd_capture", task="shd", windows=(0, 1, 2, 3),
              record_layers=False) -> str:
    if task == "dvs" and len(seeds) != 1:
        raise ValueError("A DVS job runs one seed with both model variants")
    variants = VARIANTS if task == "shd" else ("original", "floor_repaired")
    runners = ["run_spinnaker1_matrix.py", "run_spinnaker1_shd.py"]
    if task == "dvs":
        runners.append("run_spinnaker1_dvs.py")
    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as packed:
        for path in sorted((runtime / "src" / "pines").rglob("*.py")):
            packed.write(path, path.relative_to(runtime).as_posix())
        for name in runners:
            packed.write(runtime / "experiments" / name, "experiments/" + name)
        for seed in seeds:
            for variant in variants:
                name = f"models/{seed}/{variant}.npz"
                packed.write(bundle / name, "bundle/" + name)
        packed.write(inputs, "bundle/" + inputs.name)
        for name in ("bundle.json", "DATA_LICENSE.md"):
            if (bundle / name).exists():
                packed.write(bundle / name, "bundle/" + name)
    encoded = base64.b64encode(archive.getvalue()).decode("ascii")
    options = dict(inputs=inputs.name, seeds=list(seeds), start=start, count=count,
                   time_scale_factor=time_scale_factor, run_output=run_output,
                   task=task, windows=list(windows), record_layers=record_layers)
    return f'''"""Self-contained PINES hardware job generated by build_spinnaker1_nmpi_job.py."""
import base64
import io
import json
from pathlib import Path
import runpy
import shutil
import sys
import zipfile

options = json.loads({json.dumps(options)!r})
payload = {encoded!r}
root = Path("pines_job_payload").resolve()
root.mkdir(exist_ok=False)
with zipfile.ZipFile(io.BytesIO(base64.b64decode(payload))) as archive:
    archive.extractall(root)
output = Path(options["run_output"]).resolve()
sys.path.insert(0, str(root / "experiments"))
runner = "run_spinnaker1_matrix.py" if options["task"] == "shd" else "run_spinnaker1_dvs.py"
sys.argv = [str(root / "experiments" / runner),
    "--bundle", str(root / "bundle"),
    "--inputs", str(root / "bundle" / options["inputs"]),
    "--output", str(output), "--start", str(options["start"]),
    "--count", str(options["count"]),
    "--time-scale-factor", str(options["time_scale_factor"])]
if options["task"] == "shd":
    sys.argv.extend(["--seeds", *map(str, options["seeds"])])
else:
    sys.argv.extend(["--seed", str(options["seeds"][0]),
                     "--windows", *map(str, options["windows"])])
    if options["record_layers"]:
        sys.argv.append("--record-layers")
print("PINES batch configuration:", json.dumps(options), flush=True)
try:
    runpy.run_path(sys.argv[0], run_name="__main__")
finally:
    # NMPI publishes individual files by basename. The ZIP preserves per-input
    # folders, including partial captures when the experiment raises an error.
    if output.exists():
        shutil.make_archive(str(output) + "_capture", "zip", root_dir=output)
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--bundle", type=Path, required=True)
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seeds", type=int, nargs="+", default=list(SEEDS))
    parser.add_argument("--start", type=int, default=0)
    parser.add_argument("--count", type=int, default=1)
    parser.add_argument("--time-scale-factor", type=int, default=100)
    parser.add_argument("--run-output", default="batch_shd_capture")
    parser.add_argument("--task", choices=("shd", "dvs"), default="shd")
    parser.add_argument("--windows", type=int, nargs="+", choices=(0, 1, 2, 3), default=[0, 1, 2, 3])
    parser.add_argument("--record-layers", action="store_true")
    args = parser.parse_args()
    source = build_job(args.runtime, args.bundle, args.inputs, seeds=args.seeds,
        start=args.start, count=args.count, time_scale_factor=args.time_scale_factor,
        run_output=args.run_output, task=args.task, windows=args.windows,
        record_layers=args.record_layers)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("x", encoding="utf-8") as output:
        output.write(source)
    print(f"Created {args.output.name}: {len(source):,} characters. Not yet submitted.")
